def kana_to_hangul(text):
    # Sort keys by length descending to match 2-char youon first
    keys = sorted(KANA_TO_HANGUL.keys(), key=len, reverse=True)
    res = ""
    i = 0
    while i < len(text):
        found = False
        for k in keys:
            if text.startswith(k, i):
                res += KANA_TO_HANGUL[k]
                i += len(k)
                found = True
                break
        if not found:
            res += text[i]
            i += 1
    # Very basic fix for 'ㅅ' (sokuon) - usually functions as batchim, but we can leave it as ㅅ
    # or attach it to previous character. For simplicity, we just leave it as 'ㅅ' or '-' which users understand.
    return res

